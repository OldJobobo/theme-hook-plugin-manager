#!/usr/bin/env bash
source "${THPM_THEME_ENV:-$HOME/.local/share/thpm/lib/theme-env.sh}"

# Emacs & Doom Emacs theme and font synchronization plugin for Omarchy.

has_emacs_cmd=0
command -v emacs >/dev/null 2>&1 && has_emacs_cmd=1

emacs_dirs=()
doom_dirs=()

for dir in "$HOME/.config/emacs" "$HOME/.emacs.d"; do
    if [[ -d "$dir" ]]; then
        emacs_dirs+=("$dir")
    fi
done

for dir in "$HOME/.config/doom" "$HOME/.doom.d"; do
    if [[ -d "$dir" ]]; then
        doom_dirs+=("$dir")
    fi
done

if [[ $has_emacs_cmd -eq 0 && ${#emacs_dirs[@]} -eq 0 && ${#doom_dirs[@]} -eq 0 ]]; then
    skipped "Emacs"
fi

if [[ -z "${primary_background:-}" || -z "${primary_foreground:-}" ]]; then
    if declare -F skipped >/dev/null 2>&1; then
        skipped "Emacs theme colors"
    fi
    exit 0
fi

target_dirs=()
if [[ ${#emacs_dirs[@]} -gt 0 ]]; then
    for dir in "${emacs_dirs[@]}"; do
        target_dirs+=("$dir")
    done
fi

if [[ ${#doom_dirs[@]} -gt 0 ]]; then
    for dir in "${doom_dirs[@]}"; do
        target_dirs+=("$dir")
    done
fi

if [[ ${#target_dirs[@]} -eq 0 ]]; then
    target_dirs+=("${XDG_CONFIG_HOME:-$HOME/.config}/emacs")
fi

accent_color="${normal_blue:-$primary_foreground}"
cursor_col="${cursor_color:-$primary_foreground}"
sel_fg="${selection_foreground:-$primary_background}"
sel_bg="${selection_background:-$normal_blue}"

light_mode="nil"
if [[ -f "${THPM_LIGHT_MODE_FILE:-}" ]] || [[ "${mode:-}" == "light" ]]; then
    light_mode="t"
fi

for target_dir in "${target_dirs[@]}"; do
    mkdir -p "$target_dir/themes"

    cat > "$target_dir/omarchy-colors.el" <<EOF
;;; omarchy-colors.el --- Generated by Omarchy THPM -*- lexical-binding: t -*-
;;; Do not edit - this file is regenerated on theme changes.

(setq omarchy-color-accent "#${accent_color}")
(setq omarchy-color-cursor "#${cursor_col}")
(setq omarchy-color-fg "#${primary_foreground}")
(setq omarchy-color-bg "#${primary_background}")
(setq omarchy-color-sel-fg "#${sel_fg}")
(setq omarchy-color-sel-bg "#${sel_bg}")

(setq omarchy-color-black "#${normal_black}")
(setq omarchy-color-red "#${normal_red}")
(setq omarchy-color-green "#${normal_green}")
(setq omarchy-color-yellow "#${normal_yellow}")
(setq omarchy-color-blue "#${normal_blue}")
(setq omarchy-color-magenta "#${normal_magenta}")
(setq omarchy-color-cyan "#${normal_cyan}")
(setq omarchy-color-white "#${normal_white}")
(setq omarchy-color-bright-black "#${bright_black}")
(setq omarchy-color-bright-red "#${bright_red}")
(setq omarchy-color-bright-green "#${bright_green}")
(setq omarchy-color-bright-yellow "#${bright_yellow}")
(setq omarchy-color-bright-blue "#${bright_blue}")
(setq omarchy-color-bright-magenta "#${bright_magenta}")
(setq omarchy-color-bright-cyan "#${bright_cyan}")
(setq omarchy-color-bright-white "#${bright_white}")
(setq omarchy-is-light ${light_mode})

(provide 'omarchy-colors)
;;; omarchy-colors.el ends here
EOF

    cp "$target_dir/omarchy-colors.el" "$target_dir/themes/omarchy-colors.el"

    cat > "$target_dir/themes/omarchy-theme.el" <<'EOF'
;;; omarchy-theme.el --- Omarchy theme synced from system colors -*- lexical-binding: t -*-

(deftheme omarchy "Omarchy theme synced from system colors.")

(require 'omarchy-colors nil t)

