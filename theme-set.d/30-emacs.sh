    cat > "$target_dir/omarchy.el" <<'EOF'
;;; omarchy.el --- Omarchy Emacs & Doom Emacs integration -*- lexical-binding: t -*-

(require 'subr-x)
(require 'cl-lib)

;; Add theme directories to custom-theme-load-path (do not add user-emacs-directory to load-path)
(let ((cfg-dir (or (bound-and-true-p doom-user-dir)
                   (bound-and-true-p user-emacs-directory)
                   (file-name-directory (or load-file-name buffer-file-name "~/.config/emacs/omarchy.el")))))
  (when (and cfg-dir (file-directory-p cfg-dir))
    (let ((themes-dir (expand-file-name "themes" cfg-dir)))
      (when (file-directory-p themes-dir)
        (add-to-list 'custom-theme-load-path themes-dir)))))

(dolist (d '("~/.config/emacs/themes" "~/.emacs.d/themes" "~/.config/doom/themes" "~/.doom.d/themes"))
  (let ((expanded (expand-file-name d)))
    (when (file-directory-p expanded)
      (add-to-list 'custom-theme-load-path expanded))))

(defun omarchy-light-theme-p ()
  "Return non-nil if the current Omarchy theme is a light theme."
  (or (bound-and-true-p omarchy-is-light)
      (file-exists-p "~/.local/state/omarchy/current/theme/light.mode")
      (file-exists-p "~/.config/omarchy/current/theme/light.mode")))

(defun omarchy-apply-theme ()
  "Load Omarchy colors and apply them as an Emacs / Doom Emacs theme."
  (interactive)
  (let* ((cfg-dir (or (bound-and-true-p doom-user-dir)
                      (bound-and-true-p user-emacs-directory)
                      "~/.config/emacs"))
         (colors-file (or (locate-file "omarchy-colors.el" custom-theme-load-path '(".el"))
                          (expand-file-name "omarchy-colors.el" cfg-dir)
                          (expand-file-name "omarchy-colors.el" "~/.emacs.d"))))
    (when (and colors-file (file-exists-p colors-file))
      (load-file colors-file)))
  (dolist (theme '(omarchy omarchy-dark omarchy-light))
    (disable-theme theme)
    (put theme 'theme-settings nil)
    (setq custom-known-themes (delq theme custom-known-themes)))
  (let ((theme-file (locate-file "omarchy-theme" custom-theme-load-path '(".el"))))
    (when theme-file
      (load-file theme-file)))
  (enable-theme 'omarchy)
  (when (boundp 'doom-theme)
    (setq doom-theme 'omarchy))
  (when (fboundp 'doom-modeline-refresh-bars)
    (ignore-errors (doom-modeline-refresh-bars))))

(defun omarchy--match-in-file (file regex &optional group)
  (let ((path (expand-file-name file)))
    (when (file-readable-p path)
      (with-temp-buffer
        (insert-file-contents path)
        (goto-char (point-min))
        (when (re-search-forward regex nil t)
          (match-string (or group 1)))))))

(defun omarchy--current-terminal ()
  (let* ((dirs '("~/.local/share/applications" "/usr/share/applications" "/usr/local/share/applications"))
         (installed (lambda (entry)
                      (and (stringp entry) (not (string-empty-p entry))
                           (cl-some (lambda (d) (file-exists-p (expand-file-name entry d))) dirs))))
         (list-file (expand-file-name "~/.config/xdg-terminals.list"))
         (entries (when (file-readable-p list-file)
                    (with-temp-buffer
                      (insert-file-contents list-file)
                      (mapcar (lambda (l) (string-trim (replace-regexp-in-string "#.*" "" l)))
                              (split-string (buffer-string) "\n")))))
         (entry (or (cl-find-if installed entries)
                    (cl-find-if installed '("com.mitchellh.ghostty.desktop" "kitty.desktop" "Alacritty.desktop")))))
    (when entry
      (cond
       ((string-match-p "[Aa]lacritty" entry) 'alacritty)
       ((string-match-p "kitty" entry) 'kitty)
       ((string-match-p "ghostty" entry) 'ghostty)))))

(defun omarchy--terminal-font-size ()
  (pcase (omarchy--current-terminal)
    ('alacritty
     (let ((file (expand-file-name "~/.config/alacritty/alacritty.toml")))
       (when (file-readable-p file)
         (with-temp-buffer
           (insert-file-contents file)
           (goto-char (point-min))
           (when (re-search-forward "^\\[font\\][ \t]*$" nil t)
             (let ((bound (or (save-excursion (when (re-search-forward "^\\[" nil t) (match-beginning 0))) (point-max))))
               (when (re-search-forward "^size[ \t]*=[ \t]*\\([0-9]+\\(?:\\.[0-9]+\\)?\\)" bound t)
                 (match-string 1))))))))
    ('kitty (omarchy--match-in-file "~/.config/kitty/kitty.conf" "^font_size[ \t]+\\([0-9]+\\(?:\\.[0-9]+\\)?\\)"))
    ('ghostty (omarchy--match-in-file "~/.config/ghostty/config" "^font-size[ \t]*=[ \t]*\\([0-9]+\\(?:\\.[0-9]+\\)?\\)"))))

(defun omarchy--terminal-font-family ()
  (pcase (omarchy--current-terminal)
    ('alacritty
     (let ((file (expand-file-name "~/.config/alacritty/alacritty.toml")))
       (when (file-readable-p file)
         (with-temp-buffer
           (insert-file-contents file)
           (goto-char (point-min))
           (when (re-search-forward "^\\[font\\][ \t]*$" nil t)
             (let ((bound (or (save-excursion (when (re-search-forward "^\\[" nil t) (match-beginning 0))) (point-max))))
               (when (re-search-forward "family[ \t]*=[ \t]*[\"']\\([^\"']+\\)[\"']" bound t)
                 (match-string 1))))))))
    ('kitty (omarchy--match-in-file "~/.config/kitty/kitty.conf" "^font_family[ \t]+\\(.+?\\)[ \t]*$"))
    ('ghostty (omarchy--match-in-file "~/.config/ghostty/config" "^font-family[ \t]*=[ \t]*[\"']?\\([^\"'\n]+?\\)[\"']?[ \t]*$" ))
    ('foot (omarchy--match-in-file "~/.config/foot/foot.ini" "^font[ \t]*=[ \t]*\\([^:\n]+\\)"))))

(defun omarchy-current-font ()
  (or (let ((fam (omarchy--terminal-font-family)))
        (and fam (setq fam (string-trim fam)) (not (string-empty-p fam)) fam))
      (and (executable-find "omarchy-font-current")
           (let ((f (string-trim (shell-command-to-string "omarchy-font-current"))))
             (and (not (string-empty-p f)) f)))
      (omarchy--match-in-file "~/.config/waybar/style.css" "font-family:[ \t]*[\"']?\\([^;\"'\n]+\\)")
      ""))

(defun omarchy-current-font-size ()
  (let ((size (omarchy--terminal-font-size)))
    (round (* (if size (string-to-number size) 12.0) 10))))

(defun omarchy-apply-font ()
  "Set default font for standard Emacs & Doom Emacs."
  (let ((font (omarchy-current-font))
        (pt (/ (omarchy-current-font-size) 10.0)))
    (when (and font (not (string-empty-p font)))
      (let ((spec
             (if (featurep 'pgtk)
                 (format "%s:pixelsize=%d" font (max 1 (round (* pt (/ 96.0 72.0)))))
               (let ((s (string-to-number
                         (string-trim
                          (shell-command-to-string
                           "hyprctl monitors 2>/dev/null | grep -oP 'scale:\\s*\\K[0-9]+\\.?[0-9]*' | head -1")))))
                 (format "%s-%g" font (* pt (if (or (zerop s) (< s 1)) 1.0 s)))))))
        (set-face-attribute 'default nil :font spec)
        (dolist (frame (frame-list))
          (when (display-graphic-p frame)
            (set-frame-font spec nil (list frame))))
        (setf (alist-get 'font default-frame-alist) spec)
        (when (boundp 'doom-font)
          (setq doom-font (font-spec :family font :size pt)))))))

(unless (boundp 'doom-version)
  (menu-bar-mode -1)
  (tool-bar-mode -1)
  (scroll-bar-mode -1)
  (set-frame-parameter nil 'internal-border-width 8)
  (add-to-list 'default-frame-alist '(internal-border-width . 8)))

(omarchy-apply-theme)
(omarchy-apply-font)

(provide 'omarchy)
;;; omarchy.el ends here
EOF

    # Cleanly load omarchy without adding user-emacs-directory to load-path
    if [[ "$target_dir" == *doom* ]]; then
        config_file="$target_dir/config.el"
        if [[ ! -f "$config_file" ]]; then
            cat > "$config_file" <<'EOF'
;;; config.el --- Doom Emacs configuration -*- lexical-binding: t -*-

;; Load Omarchy theme and font integration
(let ((omarchy-file (expand-file-name "omarchy.el" (or (bound-and-true-p doom-user-dir) "~/.config/doom"))))
  (when (file-exists-p omarchy-file)
    (load omarchy-file nil t)))
EOF
        elif ! grep -Fq "omarchy" "$config_file"; then
            sed -i '/add-to-list '\''load-path dir/d' "$config_file" 2>/dev/null || true
            printf '\n;; Load Omarchy integration\n(let ((omarchy-file (expand-file-name "omarchy.el" (or (bound-and-true-p doom-user-dir) "~/.config/doom"))))\n  (when (file-exists-p omarchy-file)\n    (load omarchy-file nil t)))\n' >> "$config_file"
        fi
    else
        init_file="$target_dir/init.el"
        cat > "$init_file" <<'EOF'
;;; init.el --- Emacs initialisation -*- lexical-binding: t -*-

;; Load Omarchy theme and font integration
(let ((omarchy-file (expand-file-name "omarchy.el" (or (bound-and-true-p user-emacs-directory) "~/.config/emacs"))))
  (when (file-exists-p omarchy-file)
    (load omarchy-file nil t)))

;; Add your personal customizations below this line
EOF
    fi

done

if command -v emacsclient >/dev/null 2>&1 && emacsclient --eval t >/dev/null 2>&1; then
    emacsclient --no-wait --eval \
      "(progn
         (dolist (dir '(\"~/.config/emacs\" \"~/.emacs.d\" \"~/.config/doom\" \"~/.doom.d\"))
           (let ((f (expand-file-name \"omarchy.el\" (expand-file-name dir))))
             (when (file-exists-p f) (load-file f))))
         (when (fboundp 'omarchy-apply-theme) (omarchy-apply-theme))
         (when (fboundp 'omarchy-apply-font) (omarchy-apply-font)))" >/dev/null 2>&1 || true
    success "Emacs theme updated!"
else
    require_restart "emacs" "Emacs"
    success "Emacs theme files generated!"
fi
