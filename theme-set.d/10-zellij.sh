#!/usr/bin/env bash
source "${THPM_THEME_ENV:-$HOME/.local/share/thpm/lib/theme-env.sh}"

if ! command -v zellij >/dev/null 2>&1; then
    skipped "Zellij"
fi

theme_dir="$HOME/.config/zellij/themes"
output_file="$theme_dir/current.kdl"
source_file="$HOME/.config/omarchy/current/theme/zellij.kdl"

mkdir -p "$theme_dir"

{
    printf '// Generated by thpm zellij plugin. Do not edit directly.\n'
    printf '// Set `theme "current"` in ~/.config/zellij/config.kdl to use this theme.\n\n'

    if [[ -f "$source_file" ]]; then
        cat "$source_file"
    else
        cat <<EOF
themes {
    current {
        text_unselected {
            base ${rgb_primary_foreground//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_yellow//,/}
