            emphasis_1 ${rgb_normal_yellow//,/}
            emphasis_2 ${rgb_bright_yellow//,/}
            emphasis_3 ${rgb_normal_red//,/}
        }
        exit_code_success {
            base ${rgb_normal_green//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_cyan//,/}
            emphasis_1 ${rgb_selection_background//,/}
            emphasis_2 ${rgb_normal_magenta//,/}
            emphasis_3 ${rgb_normal_blue//,/}
        }
        exit_code_error {
            base ${rgb_normal_red//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_yellow//,/}
            emphasis_1 ${rgb_primary_background//,/}
            emphasis_2 ${rgb_primary_background//,/}
            emphasis_3 ${rgb_primary_background//,/}
