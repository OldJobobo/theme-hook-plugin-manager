            emphasis_2 ${rgb_normal_green//,/}
            emphasis_3 ${rgb_normal_magenta//,/}
        }
        text_selected {
            base ${rgb_selection_foreground//,/}
            background ${rgb_selection_background//,/}
            emphasis_0 ${rgb_bright_yellow//,/}
            emphasis_1 ${rgb_bright_cyan//,/}
            emphasis_2 ${rgb_bright_green//,/}
            emphasis_3 ${rgb_bright_magenta//,/}
        }
        ribbon_selected {
            base ${rgb_primary_background//,/}
            background ${rgb_normal_blue//,/}
            emphasis_0 ${rgb_normal_red//,/}
            emphasis_1 ${rgb_normal_yellow//,/}
            emphasis_2 ${rgb_normal_magenta//,/}
            emphasis_3 ${rgb_normal_cyan//,/}
        }
        ribbon_unselected {
            base ${rgb_primary_foreground//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_bright_red//,/}
            emphasis_1 ${rgb_bright_yellow//,/}
            emphasis_2 ${rgb_bright_cyan//,/}
            emphasis_3 ${rgb_bright_magenta//,/}
        }
        table_title {
            base ${rgb_normal_blue//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_yellow//,/}
            emphasis_1 ${rgb_normal_cyan//,/}
            emphasis_2 ${rgb_normal_green//,/}
            emphasis_3 ${rgb_normal_magenta//,/}
        }
        table_cell_selected {
            base ${rgb_selection_foreground//,/}
            background ${rgb_selection_background//,/}
            emphasis_0 ${rgb_bright_yellow//,/}
            emphasis_1 ${rgb_bright_cyan//,/}
            emphasis_2 ${rgb_bright_green//,/}
            emphasis_3 ${rgb_bright_magenta//,/}
        }
        table_cell_unselected {
            base ${rgb_primary_foreground//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_yellow//,/}
            emphasis_1 ${rgb_normal_cyan//,/}
            emphasis_2 ${rgb_normal_green//,/}
            emphasis_3 ${rgb_normal_magenta//,/}
        }
        list_selected {
            base ${rgb_selection_foreground//,/}
            background ${rgb_selection_background//,/}
            emphasis_0 ${rgb_bright_yellow//,/}
            emphasis_1 ${rgb_bright_cyan//,/}
            emphasis_2 ${rgb_bright_green//,/}
            emphasis_3 ${rgb_bright_magenta//,/}
        }
        list_unselected {
            base ${rgb_primary_foreground//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_yellow//,/}
            emphasis_1 ${rgb_normal_cyan//,/}
            emphasis_2 ${rgb_normal_green//,/}
            emphasis_3 ${rgb_normal_magenta//,/}
        }
        frame_selected {
            base ${rgb_normal_blue//,/}
            background ${rgb_primary_background//,/}
            emphasis_0 ${rgb_normal_yellow//,/}
            emphasis_1 ${rgb_normal_cyan//,/}
            emphasis_2 ${rgb_normal_magenta//,/}
            emphasis_3 ${rgb_primary_background//,/}
        }
        frame_highlight {
            base ${rgb_normal_yellow//,/}
            background ${rgb_primary_background//,/}
